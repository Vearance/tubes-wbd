import http from 'k6/http';
import exec from 'k6/execution';
import { check, sleep } from 'k6';
import { Counter, Rate, Trend } from 'k6/metrics';

// ============================================================================
// 1. Configuration & Load Stages
// ============================================================================
// Load profile moves through 4 equal-duration stages:
//   normal -> high -> stress -> recovery (drops back to normal to verify recovery)

const BASE_URL = (__ENV.BASE_URL || 'http://localhost:8080').replace(/\/+$/, '');
const FIXTURE_PATH = __ENV.FIXTURE_PATH || './.k6-fixture.json';
const SUMMARY_PATH = __ENV.SUMMARY_PATH || './results/summary.json';
const IS_QUICK = __ENV.QUICK === '1' || __ENV.QUICK === 'true';

const STAGE_SEC = Number(__ENV.STAGE_SEC || (IS_QUICK ? 20 : 60));
const RAMP_SEC = Number(__ENV.RAMP_SEC || (IS_QUICK ? 5 : 10));
const HOLD_SEC = Math.max(5, STAGE_SEC - RAMP_SEC);
const POLL_INTERVAL_SEC = Number(__ENV.POLL_INTERVAL_SEC || 0.5);
const POLL_TIMEOUT_SEC = Number(__ENV.POLL_TIMEOUT_SEC || (IS_QUICK ? 60 : 120));

// Concurrent Virtual Users (VUs) for general API reads/queries
const API_VUS = {
  normal: Number(__ENV.API_NORMAL_VUS || (IS_QUICK ? 5 : 10)),
  high: Number(__ENV.API_HIGH_VUS || (IS_QUICK ? 25 : 80)),
  stress: Number(__ENV.API_STRESS_VUS || (IS_QUICK ? 60 : 220)),
  recovery: Number(__ENV.API_RECOVERY_VUS || (IS_QUICK ? 5 : 10)),
};

// Arrival rates (jobs/minute) for pre-approved migrations targeting 1 shared DB vs 3 separate DBs
const SAME_RPM = {
  normal: Number(__ENV.SAME_NORMAL_RPM || (IS_QUICK ? 6 : 4)),
  high: Number(__ENV.SAME_HIGH_RPM || (IS_QUICK ? 18 : 18)),
  stress: Number(__ENV.SAME_STRESS_RPM || (IS_QUICK ? 36 : 48)),
  recovery: Number(__ENV.SAME_RECOVERY_RPM || (IS_QUICK ? 6 : 4)),
};
const DIFF_RPM = {
  normal: Number(__ENV.DIFF_NORMAL_RPM || (IS_QUICK ? 12 : 9)),
  high: Number(__ENV.DIFF_HIGH_RPM || (IS_QUICK ? 36 : 36)),
  stress: Number(__ENV.DIFF_STRESS_RPM || (IS_QUICK ? 60 : 90)),
  recovery: Number(__ENV.DIFF_RECOVERY_RPM || (IS_QUICK ? 12 : 9)),
};

const STAGES = ['normal', 'high', 'stress', 'recovery'];
const MODES = ['same_db', 'diff_db'];
const TERMINAL = { success: true, failed: true, partial: true, rejected: true, compensated: true };

// Fixture generated by run-stress-test.sh containing sessions, DB IDs, and pre-approved execution IDs
const fixture = JSON.parse(open(FIXTURE_PATH));

// ============================================================================
// 2. Custom Metrics (Overall, Per-Stage, and Same-DB vs Diff-DB)
// ============================================================================
// NOTE: API metrics exclude background worker polling requests.
// NOTE: Enqueue HTTP 202 acceptance is tracked separately from terminal migration success.

const apiReqDuration = new Trend('api_req_duration', true);
const apiReqs = new Counter('api_reqs');
const apiErrorRate = new Rate('api_error_rate');

const migAccepted = new Counter('migration_enqueue_accepted');
const migSucceeded = new Counter('migration_jobs_succeeded');
const migFailed = new Counter('migration_jobs_failed');
const migJobErrorRate = new Rate('migration_job_error_rate');
const migQueueWaitMs = new Trend('migration_queue_wait_ms', true);
const migExecDurMs = new Trend('migration_exec_duration_ms', true);

// Per-stage API metrics (used to observe degradation under stress and recovery afterward)
const apiStage = Object.fromEntries(STAGES.map((s) => [s, {
  dur: new Trend(`api_duration_${s}`, true),
  reqs: new Counter(`api_reqs_${s}`),
  err: new Rate(`api_error_rate_${s}`),
}]));

// Per-stage and per-target-mode migration metrics (attributed to the stage when the job was submitted)
const migByGroup = (keys) => Object.fromEntries(keys.map((k) => [k, {
  acc: new Counter(`mig_accepted_${k}`),
  ok: new Counter(`mig_succeeded_${k}`),
  fail: new Counter(`mig_failed_${k}`),
  err: new Rate(`mig_job_error_rate_${k}`),
  qWait: new Trend(`mig_queue_wait_${k}`, true),
  execDur: new Trend(`mig_exec_duration_${k}`, true),
}]));
const migStage = migByGroup(STAGES);
const migMode = migByGroup(MODES);

// ============================================================================
// 3. k6 Scenarios & SLO Thresholds
// ============================================================================

// Expand stage targets into [ramp, hold] pairs for each of the 4 phases
const makeStages = (cfg) => STAGES.flatMap((s) => [
  { duration: `${RAMP_SEC}s`, target: cfg[s] },
  { duration: `${HOLD_SEC}s`, target: cfg[s] },
]);

export const options = {
  summaryTrendStats: ['avg', 'min', 'med', 'p(90)', 'p(95)', 'p(99)', 'max', 'count'],
  scenarios: {
    // Scenario A: Concurrent authenticated API reads and viewer queries
    api_access: {
      executor: 'ramping-vus',
      startVUs: 1,
      stages: makeStages(API_VUS),
      gracefulRampDown: '5s',
      gracefulStop: '10s',
      exec: 'runApiAccess',
    },
    // Scenario B: Pre-approved migrations contending on 1 shared database (serialized by lock)
    migrations_same_db: {
      executor: 'ramping-arrival-rate',
      startRate: 1,
      timeUnit: '1m',
      preAllocatedVUs: 15,
      maxVUs: 80,
      stages: makeStages(SAME_RPM),
      gracefulStop: IS_QUICK ? '65s' : '130s',
      exec: 'runSameDbMigration',
    },
    // Scenario C: Pre-approved migrations distributed across 3 separate databases (parallel across workers)
    migrations_diff_db: {
      executor: 'ramping-arrival-rate',
      startRate: 1,
      timeUnit: '1m',
      preAllocatedVUs: 20,
      maxVUs: 90,
      stages: makeStages(DIFF_RPM),
      gracefulStop: IS_QUICK ? '65s' : '130s',
      exec: 'runDiffDbMigration',
    },
  },
  thresholds: {
    // API p95 response time & HTTP error rate SLOs
    'http_req_duration{kind:api}': ['p(95)<500'],
    api_req_duration: ['p(95)<500'],
    api_duration_normal: ['p(95)<150'],
    api_duration_recovery: ['p(95)<250'],
    http_req_failed: ['rate<0.01'],
    api_error_rate: ['rate<0.01'],
    // Terminal migration execution failure rate SLO
    migration_job_error_rate: ['rate<0.05'],
  },
};

// Shared helpers
function currentStage() {
  const sec = (exec.instance.currentTestRunDuration || 0) / 1000;
  return STAGES[Math.min(STAGES.length - 1, Math.floor(sec / STAGE_SEC))];
}

function authHeaders(session, isJson = false) {
  return isJson
    ? { Cookie: session.cookie, 'X-CSRF-Token': session.csrf, 'Content-Type': 'application/json' }
    : { Cookie: session.cookie, 'X-CSRF-Token': session.csrf };
}

function pickSession() {
  return fixture.sessions[(exec.vu.idInTest + exec.scenario.iterationInTest) % fixture.sessions.length];
}

// ============================================================================
// 4. Scenario A: API Access Workload
// ============================================================================
// Simulates realistic UI/API traffic across schema browser, table rows, SQL query, and migration history.

export function runApiAccess() {
  const stage = currentStage();
  const session = pickSession();
  const dbId = fixture.databaseIds[(exec.vu.idInTest + exec.vu.iterationInScenario) % fixture.databaseIds.length];
  const r = Math.random();
  const params = { headers: authHeaders(session), tags: { kind: 'api', stage } };

  let res;
  if (r < 0.15) res = http.get(`${BASE_URL}/databases`, params);
  else if (r < 0.30) res = http.get(`${BASE_URL}/databases/${dbId}/schemas`, params);
  else if (r < 0.45) res = http.get(`${BASE_URL}/databases/${dbId}/tables?schema=public`, params);
  else if (r < 0.60) res = http.get(`${BASE_URL}/databases/${dbId}/table-structure?schema=public&table=trainees`, params);
  else if (r < 0.75) res = http.get(`${BASE_URL}/databases/${dbId}/table-rows?schema=public&table=trainees&page=1&page_size=25`, params);
  else if (r < 0.90) {
    const body = JSON.stringify({
      sql: 'SELECT t.id, t.name, tm.name AS team_name FROM public.trainees t LEFT JOIN public.teams tm ON tm.id = t.team_id ORDER BY t.id LIMIT 25',
      page: 1,
      page_size: 25,
    });
    res = http.post(`${BASE_URL}/databases/${dbId}/query`, body, { headers: authHeaders(session, true), tags: { kind: 'api', stage } });
  } else {
    res = http.get(`${BASE_URL}/databases/${dbId}/migrations/history?page=1&page_size=20`, params);
  }

  const ok = check(res, { 'api status 200': (resp) => resp.status === 200 });
  apiReqDuration.add(res.timings.duration);
  apiReqs.add(1);
  apiErrorRate.add(ok ? 0 : 1);
  apiStage[stage].dur.add(res.timings.duration);
  apiStage[stage].reqs.add(1);
  apiStage[stage].err.add(ok ? 0 : 1);
  sleep(0.03 + Math.random() * 0.04);
}

// ============================================================================
// 5. Scenarios B & C: Pre-Approved Migration Enqueue & Status Polling
// ============================================================================

export function runSameDbMigration() { runMigration(fixture.sameDbExecutionIds, 'same_db'); }
export function runDiffDbMigration() { runMigration(fixture.diffDbExecutionIds, 'diff_db'); }

function recordFailure(stage, mode) {
  migFailed.add(1);
  migStage[stage].fail.add(1);
  migMode[mode].fail.add(1);
  migJobErrorRate.add(1);
  migStage[stage].err.add(1);
  migMode[mode].err.add(1);
}

function runMigration(poolIds, mode) {
  const stage = currentStage();
  const idx = exec.scenario.iterationInTest;
  if (!poolIds || idx >= poolIds.length) {
    recordFailure(stage, mode);
    return;
  }

  const executionId = poolIds[idx];
  const session = pickSession();
  const enqueueStartMs = Date.now();

  // Step 1: Enqueue pre-approved execution (expects HTTP 202 Accepted)
  const enqRes = http.post(`${BASE_URL}/migrations/executions/${executionId}/enqueue`, null, {
    headers: authHeaders(session),
    tags: { kind: 'migration_enqueue', mode, stage },
  });

  if (!check(enqRes, { 'enqueue accepted (202/200)': (r) => r.status === 202 || r.status === 200 })) {
    recordFailure(stage, mode);
    return;
  }

  // Enqueue 202 ONLY confirms queuing; actual execution success is determined after polling below.
  migAccepted.add(1);
  migStage[stage].acc.add(1);
  migMode[mode].acc.add(1);

  // Step 2: Poll execution status until terminal state or timeout
  const deadlineMs = Date.now() + POLL_TIMEOUT_SEC * 1000;
  let clientStartMs = null;

  while (Date.now() < deadlineMs) {
    sleep(POLL_INTERVAL_SEC);
    const pollRes = http.get(`${BASE_URL}/migrations/executions/${executionId}`, {
      headers: authHeaders(session),
      tags: { kind: 'migration_poll', mode, stage },
    });
    if (pollRes.status !== 200) continue;

    let payload;
    try { payload = pollRes.json(); } catch (_) { continue; }
    const status = payload && payload.status;
    if (status === 'running' && clientStartMs === null) clientStartMs = Date.now();
    if (!status || !TERMINAL[status]) continue;

    // Step 3: Record server-derived queue wait and worker execution duration
    const nowMs = Date.now();
    const queuedAtMs = payload.queued_at ? Date.parse(payload.queued_at) : enqueueStartMs;
    const startedAtMs = payload.started_at ? Date.parse(payload.started_at) : (clientStartMs || nowMs);
    const finishedAtMs = payload.finished_at ? Date.parse(payload.finished_at) : nowMs;
    const qWait = Math.max(0, startedAtMs - queuedAtMs);
    const eDur = Math.max(0, finishedAtMs - startedAtMs);

    migQueueWaitMs.add(qWait);
    migStage[stage].qWait.add(qWait);
    migMode[mode].qWait.add(qWait);
    migExecDurMs.add(eDur);
    migStage[stage].execDur.add(eDur);
    migMode[mode].execDur.add(eDur);

    if (check(payload, { 'migration status success': (p) => p.status === 'success' })) {
      migSucceeded.add(1);
      migStage[stage].ok.add(1);
      migMode[mode].ok.add(1);
      migJobErrorRate.add(0);
      migStage[stage].err.add(0);
      migMode[mode].err.add(0);
    } else {
      recordFailure(stage, mode);
    }
    return;
  }

  recordFailure(stage, mode);
}

// ============================================================================
// 6. Summary Report Builder (stdout table + results/summary.json)
// ============================================================================

const val = (d, n) => (d.metrics && d.metrics[n] && d.metrics[n].values) || {};
const trend = (d, n) => {
  const v = val(d, n);
  return { count: v.count || 0, avgMs: v.avg || 0, minMs: v.min || 0, p50Ms: v.med || 0, p95Ms: v['p(95)'] || 0, maxMs: v.max || 0 };
};
const fmtMs = (ms) => (!ms ? '0.0 ms' : ms >= 1000 ? `${(ms / 1000).toFixed(2)} s` : `${ms.toFixed(1)} ms`);

export function handleSummary(data) {
  const activeSec = STAGE_SEC * 4;
  const stageMin = STAGE_SEC / 60;

  // Aggregate metrics per load stage
  const stages = {};
  for (const s of STAGES) {
    const apiDur = trend(data, `api_duration_${s}`);
    const reqs = val(data, `api_reqs_${s}`).count || 0;
    const ok = val(data, `mig_succeeded_${s}`).count || 0;
    stages[s] = {
      durationSec: STAGE_SEC,
      api: { requests: reqs, throughputRps: reqs / STAGE_SEC, errorRate: val(data, `api_error_rate_${s}`).rate || 0, p50Ms: apiDur.p50Ms, p95Ms: apiDur.p95Ms },
      migrations: {
        enqueueAccepted: val(data, `mig_accepted_${s}`).count || 0,
        succeeded: ok,
        failed: val(data, `mig_failed_${s}`).count || 0,
        jobErrorRate: val(data, `mig_job_error_rate_${s}`).rate || 0,
        throughputPerMin: ok / stageMin,
        queueWaitMs: trend(data, `mig_queue_wait_${s}`),
        execDurationMs: trend(data, `mig_exec_duration_${s}`),
      },
    };
  }

  // Aggregate Same-DB vs Different-DB comparison
  const targetComparison = {};
  for (const m of MODES) {
    const ok = val(data, `mig_succeeded_${m}`).count || 0;
    targetComparison[m] = {
      enqueueAccepted: val(data, `mig_accepted_${m}`).count || 0,
      succeeded: ok,
      failed: val(data, `mig_failed_${m}`).count || 0,
      jobErrorRate: val(data, `mig_job_error_rate_${m}`).rate || 0,
      throughputPerMin: ok / (activeSec / 60),
      queueWaitMs: trend(data, `mig_queue_wait_${m}`),
      execDurationMs: trend(data, `mig_exec_duration_${m}`),
    };
  }

  const thresholds = Object.fromEntries(
    Object.entries(data.metrics || {}).filter(([, m]) => m.thresholds).map(([k, m]) => [k, m.thresholds]),
  );
  const overallApi = trend(data, 'api_req_duration');
  const overallReqs = val(data, 'api_reqs').count || 0;
  const overallOk = val(data, 'migration_jobs_succeeded').count || 0;

  const report = {
    config: { quick: IS_QUICK, stageSec: STAGE_SEC, rampSec: RAMP_SEC, apiVUs: API_VUS, sameDbRpm: SAME_RPM, diffDbRpm: DIFF_RPM },
    overall: {
      totalHttpReqs: val(data, 'http_reqs').count || 0,
      apiRequests: overallReqs,
      apiThroughputRps: overallReqs / activeSec,
      apiErrorRate: val(data, 'api_error_rate').rate || 0,
      apiDurationMs: overallApi,
      migrationsEnqueueAccepted: val(data, 'migration_enqueue_accepted').count || 0,
      migrationsSucceeded: overallOk,
      migrationsFailed: val(data, 'migration_jobs_failed').count || 0,
      migrationJobErrorRate: val(data, 'migration_job_error_rate').rate || 0,
      migrationThroughputPerMin: overallOk / (activeSec / 60),
      queueWaitMs: trend(data, 'migration_queue_wait_ms'),
      execDurationMs: trend(data, 'migration_exec_duration_ms'),
    },
    stages,
    targetComparison,
    thresholds,
  };

  // Format human-readable summary table for terminal output
  const lines = [
    '',
    '=== BScheme k6 Stress Test Summary ===',
    `API Overall : ${overallReqs} reqs (${(overallReqs / activeSec).toFixed(1)} req/s) | p50=${fmtMs(overallApi.p50Ms)} | p95=${fmtMs(overallApi.p95Ms)} | err=${((report.overall.apiErrorRate) * 100).toFixed(2)}%`,
    `Migrations  : ${overallOk}/${report.overall.migrationsEnqueueAccepted} succeeded (${report.overall.migrationThroughputPerMin.toFixed(1)} jobs/min)`,
    '',
    'Stage      | API req/s | API p50   | API p95   | Jobs OK/Acc | QWait p50 | QWait p95 | Exec p95  | Jobs/min',
    ...STAGES.map((s) => {
      const r = stages[s];
      return [
        s.padEnd(10),
        r.api.throughputRps.toFixed(1).padStart(9),
        fmtMs(r.api.p50Ms).padStart(9),
        fmtMs(r.api.p95Ms).padStart(9),
        `${r.migrations.succeeded}/${r.migrations.enqueueAccepted}`.padStart(11),
        fmtMs(r.migrations.queueWaitMs.p50Ms).padStart(9),
        fmtMs(r.migrations.queueWaitMs.p95Ms).padStart(9),
        fmtMs(r.migrations.execDurationMs.p95Ms).padStart(9),
        r.migrations.throughputPerMin.toFixed(1).padStart(8),
      ].join(' | ');
    }),
    '',
  ];

  return { stdout: lines.join('\n'), [SUMMARY_PATH]: JSON.stringify(report, null, 2) };
}
