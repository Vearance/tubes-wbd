#!/usr/bin/env bash
# Code coverage report for the unit and integration tests.
#
#   bash scripts/coverage.sh          unit + integration tests (requires Docker)
#   bash scripts/coverage.sh --unit   unit tests only
#
# Writes to the repository root (ignored by git):
#   coverage.out    coverage profile
#   coverage.txt    coverage per package and per function
#   coverage.html   source view with covered and uncovered lines
set -euo pipefail

cd "$(dirname "$0")/.."

tags=(-tags=integration)
label="unit + integration tests"
if [[ "${1:-}" == "--unit" ]]; then
	tags=()
	label="unit tests only"
elif [[ $# -gt 0 ]]; then
	echo "usage: $0 [--unit]" >&2
	exit 2
fi

# -coverpkg counts code exercised from any package's tests, so an integration
# test in frontend also covers auth, access, viewer, and migration.
# Excluded from the report:
#   frontend/preview          mock-data preview server, not part of the app
#   backend/http/api.gen.go   generated by oapi-codegen from api/openapi.yaml
packages=$(go list ./... | grep -v '/frontend/preview$' | paste -sd, -)

go test ${tags[@]+"${tags[@]}"} -covermode=set -coverpkg="$packages" -coverprofile=coverage.raw.out ./...
grep -v '/backend/http/api\.gen\.go:' coverage.raw.out >coverage.out
rm coverage.raw.out

{
	echo "Coverage ($label)"
	echo
	# Each package's test binary reports every block, so a block appears once
	# per binary; it is covered if any binary ran it.
	awk '
		NR == 1 { next }
		{
			if (!($1 in stmts)) {
				split($1, location, ":")
				pkg = location[1]
				sub(/\/[^\/]*$/, "", pkg)
				sub(/^tubes-wbd\//, "", pkg)
				stmts[$1] = $2
				blockPkg[$1] = pkg
			}
			if ($3 > 0) hit[$1] = 1
		}
		END {
			for (block in stmts) {
				total[blockPkg[block]] += stmts[block]
				all += stmts[block]
				if (block in hit) {
					covered[blockPkg[block]] += stmts[block]
					allCovered += stmts[block]
				}
			}
			for (pkg in total) {
				printf "%-30s %6.1f%%  (%d/%d statements)\n", pkg, 100 * covered[pkg] / total[pkg], covered[pkg], total[pkg] | "sort"
			}
			close("sort")
			printf "%-30s %6.1f%%  (%d/%d statements)\n", "total", 100 * allCovered / all, allCovered, all
		}
	' coverage.out
} | tee coverage.txt

{
	echo
	echo "Per function:"
	go tool cover -func=coverage.out
} >>coverage.txt
go tool cover -html=coverage.out -o coverage.html

echo
echo "Wrote coverage.txt and coverage.html"
